// Mapa para obtener el ícono según el slug de la categoría o el iconId
export function getCategoryIconComponent(catKeyOrIcon, className = 'w-6 h-6') {
  switch (catKeyOrIcon) {
    case 'conchas':
    case 'cookie':
      return <ConchaIcon className={className} />;
    case 'panques':
    case 'cake':
      return <PanqueIcon className={className} />;
    case 'roscas':
    case 'circle-dot':
      return <RoscaIcon className={className} />;
    case 'conchas-especialidad':
    case 'sparkles':
      return <EspecialidadIcon className={className} />;
    case 'pan-barra':
    case 'bread':
      return <PanBarraIcon className={className} />;
    case 'pan-hamburguesa':
    case 'sandwich':
      return <PanHamburguesaIcon className={className} />;
    case 'pan-banquetes':
    case 'utensils':
      return <PanBanquetesIcon className={className} />;
    case 'pan-danes':
    case 'croissant':
      return <PanDanesIcon className={className} />;
    case 'temporada':
    case 'calendar':
      return <TemporadaIcon className={className} />;
    default:
      return <GenericBakeryIcon className={className} />;
  }
}
